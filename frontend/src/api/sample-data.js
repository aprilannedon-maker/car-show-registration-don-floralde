function roundCurrency(value) {
  return Math.round((Number(value) + Number.EPSILON) * 100) / 100;
}

export async function getRegistrations({
  participantName = "",
  type = "",
  status = "",
  page = 1,
  pageSize = 10,
} = {}) {
  const normalizedName = participantName.trim().toLowerCase();
  const normalizedType = type && type !== "All" ? type.trim() : "";
  const normalizedStatus = status && status !== "All" ? status.trim() : "";

  const filtered = SAMPLE_REGISTRATIONS.filter((item) => {
    const matchesName =
      !normalizedName ||
      item.participantName.toLowerCase().includes(normalizedName);
    const matchesType =
      !normalizedType || item.registrationType === normalizedType;
    const matchesStatus =
      !normalizedStatus || item.status === normalizedStatus;
    return matchesName && matchesType && matchesStatus;
  });

  const safePageSize = Math.max(1, Number(pageSize) || 10);
  const totalCount = filtered.length;
  const totalPages = Math.max(1, Math.ceil(totalCount / safePageSize));
  const safePage = Math.min(Math.max(1, Number(page) || 1), totalPages);
  const startIndex = (safePage - 1) * safePageSize;
  const items = filtered.slice(startIndex, startIndex + safePageSize);

  return {
    items,
    page: safePage,
    pageSize: safePageSize,
    totalCount,
    totalPages: totalCount === 0 ? 0 : totalPages,
  };
}

export async function getSummary() {
  let confirmed = 0;
  let checkedIn = 0;
  let pending = 0;
  let cancelled = 0;
  let totalFees = 0;
  let totalPayments = 0;
  let uncollectedPayments = 0;

  for (const item of SAMPLE_REGISTRATIONS) {
    const fee = Number(item.registrationFee) || 0;
    const paid = Number(item.amountPaid) || 0;

    totalFees += fee;
    totalPayments += paid;

    if (item.status !== "Cancelled") {
      uncollectedPayments += Math.max(0, fee - paid);
    }

    if (item.status === "Confirmed") confirmed += 1;
    else if (item.status === "CheckedIn") checkedIn += 1;
    else if (item.status === "Pending") pending += 1;
    else if (item.status === "Cancelled") cancelled += 1;
  }

  return {
    totalRegistrations: SAMPLE_REGISTRATIONS.length,
    confirmed,
    checkedIn,
    pending,
    cancelled,
    totalFees: roundCurrency(totalFees),
    totalPayments: roundCurrency(totalPayments),
    uncollectedPayments: roundCurrency(uncollectedPayments),
  };
}